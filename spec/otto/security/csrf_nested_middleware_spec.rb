# spec/otto/security/csrf_nested_middleware_spec.rb
#
# frozen_string_literal: true

require 'spec_helper'

# CSRFMiddleware can run more than once for a request: an app may add it
# again around an Otto that already has CSRF protection, and an Otto can
# hand unmatched requests to another CSRF-enabled Otto (not_found=). Only
# the first, innermost, middleware sets the binding cookie. RFC 6265,
# section 4.1.1: "Servers SHOULD NOT include more than one Set-Cookie header
# field in the same response with the same cookie-name."
# rubocop:disable-next RSpec/DescribeClass
RSpec.describe 'CSRFMiddleware run more than once' do
  include OttoTestHelpers

  def csrf_config(secret, session_key = nil)
    Otto::Security::Config.new.tap do |c|
      c.enable_csrf_protection!
      c.csrf_secret      = secret
      c.csrf_session_key = session_key if session_key
    end
  end

  let(:config) { csrf_config('f' * 64) }
  let(:html) { '<html><head></head><body>form</body></html>' }

  def cookie_lines(headers)
    headers.select { |key, _value| key.casecmp?('set-cookie') }.values
           .flat_map { |value| Array(value) }.flat_map { |line| line.split("\n") }
  end

  def binding_cookies(headers)
    cookie_lines(headers).grep(/\A(?:__Host-otto_session|_otto_session)=/)
  end

  def wrap(app, *configs)
    configs.reduce(app) { |inner, cfg| Otto::Security::Middleware::CSRFMiddleware.new(inner, cfg) }
  end

  def call(stack, url = 'https://example.org/')
    stack.call(Rack::MockRequest.env_for(url))
  end

  describe 'with the same config twice' do
    it 'sets the binding cookie once on an HTML response' do
      app = ->(_env) { [200, { 'content-type' => 'text/html' }, [html]] }

      _, headers, = call(wrap(app, config, config))

      expect(binding_cookies(headers).size).to eq(1)
    end

    it 'sets the binding cookie once on a response that is not HTML' do
      app = lambda do |env|
        env['otto.csrf_binding'] = 'minted'
        [200, { 'content-type' => 'application/json' }, ['{}']]
      end

      _, headers, = call(wrap(app, config, config))

      expect(binding_cookies(headers)).to eq(['__Host-otto_session=minted; Path=/; HttpOnly; SameSite=Lax; Secure'])
    end

    it 'sets _otto_session once on HTTP' do
      app = ->(_env) { [200, { 'content-type' => 'text/html' }, [html]] }

      _, headers, = call(wrap(app, config, config), 'http://example.org/')

      expect(binding_cookies(headers).size).to eq(1)
      expect(binding_cookies(headers).first).to start_with('_otto_session=')
    end
  end

  describe 'with a Set-Cookie already in the response' do
    def json_call(set_cookie)
      app = lambda do |env|
        env['otto.csrf_binding'] = 'minted'
        [200, { 'content-type' => 'application/json' }.merge(set_cookie), ['{}']]
      end
      call(wrap(app, config))
    end

    it 'does not add a second cookie of the same name' do
      _, headers, = json_call('set-cookie' => ['app=1', '__Host-otto_session=other; Path=/; Secure'])

      expect(binding_cookies(headers)).to eq(['__Host-otto_session=other; Path=/; Secure'])
    end

    it 'finds the cookie in a newline-joined String' do
      _, headers, = json_call('set-cookie' => "app=1\n__Host-otto_session=other; Path=/; Secure")

      expect(binding_cookies(headers).size).to eq(1)
    end

    it 'finds the cookie under a mixed-case Set-Cookie key' do
      _, headers, = json_call('Set-Cookie' => '__Host-otto_session=other; Path=/; Secure')

      expect(binding_cookies(headers).size).to eq(1)
    end

    it 'still adds the cookie next to cookies with other names' do
      others = ['_otto_session=http', 'x__Host-otto_session=1', '__Host-otto_sessions=1', 'app=__Host-otto_session=1']

      _, headers, = json_call('set-cookie' => others)

      expect(cookie_lines(headers)).to eq([*others, '__Host-otto_session=minted; Path=/; HttpOnly; SameSite=Lax; Secure'])
    end

    it 'passes over an element of a Set-Cookie Array that is not a String' do
      _, headers, = json_call('set-cookie' => [nil, 'app=1'])

      expect(headers['set-cookie']).to eq([nil, 'app=1', '__Host-otto_session=minted; Path=/; HttpOnly; SameSite=Lax; Secure'])
    end
  end

  # Two CSRF-enabled Ottos, the outer one handing unmatched requests to the
  # inner one, whose route (and CSRF check) serves the form and the POST.
  # Without session middleware each reads and mints its binding under its
  # own csrf_session_key, so the two bindings differ. The inner Otto checks
  # the POST, so its binding is the one the client must keep: tokens the
  # inner Otto issues, injected or generated by its handlers, are bound to
  # it.
  describe 'nested Ottos whose configs differ' do
    let(:inner) do
      handlers = {
        'form' => lambda do |_req, res, _extra|
          res['content-type'] = 'text/html'
          res.write('<html><head></head><body></body></html>')
        end,
        'login' => lambda do |_req, res, _extra|
          res['content-type'] = 'text/plain'
          res.write('logged in')
        end,
      }
      routes = create_test_routes_file('test_routes_csrf_nested_inner.txt', ['GET /form &form', 'POST /login &login'])
      Otto.new(routes, lambda_handlers: handlers, csrf_protection: true).tap do |app|
        app.security_config.csrf_secret      = '1' * 64
        app.security_config.csrf_session_key = '_inner_csrf'
      end
    end

    let(:outer) do
      routes = create_test_routes_file('test_routes_csrf_nested_outer.txt', ['GET /outer &outer'])
      handlers = { 'outer' => ->(_req, res, _extra) { res.write('outer') } }
      Otto.new(routes, lambda_handlers: handlers, csrf_protection: true).tap do |app|
        app.security_config.csrf_secret      = '2' * 64
        app.security_config.csrf_session_key = '_outer_csrf'
        app.not_found = inner
      end
    end

    # Each middleware inserts its meta tag right after <head>, so the inner
    # Otto's tag, inserted first, ends up last.
    def inner_token(html) = html.scan(/name="csrf-token" content="([^"]+)"/).flatten.last

    # Like a browser, keeps the last Set-Cookie of each name.
    def cookie_jar(headers)
      cookie_lines(headers).to_h { |line| line.split(';').first.split('=', 2) }
    end

    def request(method, path, jar, params = {})
      env = Rack::MockRequest.env_for("https://example.org#{path}", method: method, params: params)
      env['HTTP_COOKIE'] = jar.map { |name, value| "#{name}=#{value}" }.join('; ') unless jar.empty?
      status, headers, body = outer.call(env)
      text = +''
      body.each { |chunk| text << chunk }
      [status, headers, text]
    end

    it "sets one binding cookie, the inner Otto's, and the inner Otto accepts its token with it" do
      _, headers, html = request('GET', '/form', {})

      expect(binding_cookies(headers).size).to eq(1)

      status, = request('POST', '/login', cookie_jar(headers), '_csrf_token' => inner_token(html))

      expect(status).to eq(200)
    end
  end
end
